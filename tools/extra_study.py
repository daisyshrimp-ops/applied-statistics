EXTRA_METHODS = r"""
**Зависимость.** Основной показатель — корреляция Спирмена (монотонная связь рангов),
дополнительно считаем Пирсона (линейная связь) и χ² для квантильных групп.
Для χ² H₀: группы сахара и спирта независимы; H₁: зависимы.
Квантильные границы рассчитываются отдельно внутри каждого типа вина; совпавшие значения не разрываем.
Разбиение получается приблизительно равным по числу строк, поскольку наблюдения округлены.
Неотвержение гипотезы о нулевой корреляции не является доказательством независимости.

**Сравнение двух типов.** Используем двусторонний Манн — Уитни с поправкой на совпадающие ранги.
Объёмы различаются, поэтому для графиков используем плотности, а не абсолютные частоты,
и одинаковые границы столбиков. На диаграммах рассеяния обе оси имеют общие пределы.
Графики строятся по исходным значениям: раздельная стандартизация групп скрыла бы различия центра и масштаба.

**Размер эффекта.** U относится к красной группе; знак коэффициента показывает направление:
отрицательный — значения красного вина чаще ниже. Ноль не означает совпадение распределений.

$$A=\frac{U_R}{n_Rn_W}=P(X_R>X_W)+\tfrac12P(X_R=X_W),\qquad r_{rb}=2A-1.$$

**Две проверки, а не два шанса найти значимость.** Для сравнений сахара и спирта применяем
поправку Холма: сортируем два p-value, умножаем их на 2 и 1 соответственно,
обеспечиваем неубывание и ограничиваем результат единицей. Сравниваем скорректированные p с α=0.05.
Проверки зависимости внутри красного вина — отдельный исследовательский блок;
основной показатель задан заранее, дополнительные тесты служат проверкой картины связи.
"""

